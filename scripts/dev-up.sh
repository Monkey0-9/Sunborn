#!/usr/bin/env bash
# =================================================================
# Sunborn local development bootstrap
#
# Brings up the real broker wiring (Postgres + Dragonfly/Redis + Qdrant)
# in Docker, writes a development .env.local if one is missing, waits for
# every dependency to report healthy, then starts the gateway in the
# foreground with that environment.
#
# Usage:  bash scripts/dev-up.sh
# Stop:   Ctrl-C (gateway), then `make docker-down` to stop the brokers.
# =================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

if ! command -v docker >/dev/null 2>&1; then
  echo "ERROR: docker is required for broker-backed local development." >&2
  echo "       Use 'bash scripts/start-all.sh' for a zero-dependency memory-only run." >&2
  exit 1
fi

if ! docker info >/dev/null 2>&1; then
  echo "ERROR: the Docker daemon is not running. Start Docker Desktop / dockerd first." >&2
  exit 1
fi

ENV_FILE=".env.local"
if [ ! -f "$ENV_FILE" ]; then
  cat > "$ENV_FILE" <<'EOF'
# Generated by scripts/dev-up.sh — local development only. Do not commit.
SUNBORN_ENV=development
HOST=127.0.0.1
PORT=8080
RUST_LOG=info,sunborn=debug,tower_http=info

# Broker wiring: these hosts are the loopback ports published by
# deploy/docker-compose.yml.
SUNBORN_CACHE_BACKEND=dragonfly
DRAGONFLY_URL=redis://127.0.0.1:6379
SUNBORN_DB_BACKEND=postgres
POSTGRES_URL=postgres://sunborn:dev_insecure_postgres_password@127.0.0.1:5432/sunborn
SUNBORN_VECTOR_BACKEND=qdrant
QDRANT_URL=http://127.0.0.1:6333
SUNBORN_STRICT_DURABILITY=false

# Development-only key material. Replace before any non-local use.
SUNBORN_MASTER_KEK=000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f
SUNBORN_ADMIN_KEY=sunborn-admin-key
SUNBORN_LEARNING_HMAC_SECRET=a0b1c2d3e4f5a0b1c2d3e4f5a0b1c2d3e4f5a0b1c2d3e4f5a0b1c2d3e4f5a0b1
SUNBORN_CERTIFICATE_SIGNING_KEY=a0b1c2d3e4f5a0b1c2d3e4f5a0b1c2d3e4f5a0b1c2d3e4f5a0b1c2d3e4f5a0b1
SUNBORN_CORS_ALLOWED_ORIGINS=http://localhost:3000,http://127.0.0.1:3000

# Leave provider keys commented out to use the built-in mock origin. A
# present-but-empty value is treated as unset by the gateway. Uncomment and
# fill these in for live upstream calls.
# SUNBORN_LLM_ORIGIN_URL=https://api.openai.com/v1
# OPENAI_API_KEY=sk-...
# SUNBORN_EMBEDDING_URL=https://api.openai.com/v1/embeddings
# SUNBORN_EMBEDDING_API_KEY=sk-...
SUNBORN_EMBEDDING_MODEL=text-embedding-3-small
EOF
  echo "Wrote $ENV_FILE (development values)."
else
  echo "Using existing $ENV_FILE."
fi

echo "Starting Postgres, Dragonfly (Redis protocol), and Qdrant..."
docker compose -f deploy/docker-compose.yml up -d postgres dragonfly qdrant

wait_healthy() {
  local name="$1"
  local i status
  for i in $(seq 1 60); do
    status="$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}no-healthcheck{{end}}' "$name" 2>/dev/null || echo missing)"
    if [ "$status" = "healthy" ]; then
      echo "  $name: healthy"
      return 0
    fi
    sleep 2
  done
  echo "ERROR: $name did not become healthy within 120s (last status: $status)." >&2
  docker compose -f deploy/docker-compose.yml logs --tail=40 "$name" >&2 || true
  return 1
}

wait_healthy sunborn-postgres
wait_healthy sunborn-dragonfly
wait_healthy sunborn-qdrant

set -a
# shellcheck disable=SC1090
. "./$ENV_FILE"
set +a

echo
echo "Brokers ready. Gateway starting on http://127.0.0.1:${PORT:-8080}"
echo "  health : curl http://127.0.0.1:${PORT:-8080}/health"
echo "  doctor : cargo run -p sunborn-gateway -- doctor"
echo "  UI     : npm --prefix frontend run dev   (http://localhost:3000)"
echo

exec cargo run -p sunborn-gateway
